/**
 * Export local SQLite rows to database/import-local-users.sql for phpMyAdmin import.
 * Run: node scripts/export-sqlite-to-mysql.js
 */
const fs = require('fs');
const path = require('path');
const { Sequelize } = require('sequelize');

function esc(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return String(value);
  const s = String(value)
    .replace(/'/g, "''")
    .replace(/\+00:00$/, '')
    .replace('T', ' ')
    .trim();
  // strip fractional timezone noise from sqlite
  const cleaned = s.replace(/ \+00:00$/, '').replace(/\.\d{3}$/, '');
  return `'${cleaned}'`;
}

function fmtDate(value) {
  if (!value) return 'NULL';
  const d = new Date(value);
  if (Number.isNaN(d.getTime())) return esc(value);
  const iso = d.toISOString().slice(0, 19).replace('T', ' ');
  return `'${iso}'`;
}

async function main() {
  const storage = process.env.DB_STORAGE || 'data/development.sqlite';
  const outPath = path.join(__dirname, '..', 'database', 'import-local-users.sql');

  const sequelize = new Sequelize({ dialect: 'sqlite', storage, logging: false });
  const [users] = await sequelize.query('SELECT * FROM users');
  const [reminders] = await sequelize.query('SELECT * FROM reminders');
  await sequelize.close();

  const userRows = users
    .map(
      (u) => `  (
    ${esc(u.id)},
    ${esc(u.full_name)},
    ${esc(u.email)},
    ${esc(u.country)},
    ${esc(u.country_code)},
    ${esc(u.mobile)},
    ${esc(u.password_hash)},
    ${esc(u.timezone)},
    ${Number(u.token_version) || 0},
    ${fmtDate(u.created_at)},
    ${fmtDate(u.updated_at)}
  )`
    )
    .join(',\n');

  const reminderRows = reminders
    .map(
      (r) => `  (
    ${esc(r.id)},
    ${esc(r.user_id)},
    ${r.title == null ? 'NULL' : esc(r.title)},
    ${esc(r.message)},
    ${esc(r.category)},
    ${fmtDate(r.scheduled_at)},
    ${esc(r.timezone)},
    ${esc(r.repeat)},
    ${esc(r.priority)},
    ${esc(r.status)},
    ${r.completed_at == null ? 'NULL' : fmtDate(r.completed_at)},
    ${r.series_id == null ? 'NULL' : esc(r.series_id)},
    ${fmtDate(r.created_at)},
    ${fmtDate(r.updated_at)}
  )`
    )
    .join(',\n');

  const sql = `-- Auto-generated by scripts/export-sqlite-to-mysql.js
-- Import in phpMyAdmin → msgreminder_prod → Import
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

${
  users.length
    ? `INSERT IGNORE INTO \`users\`
  (\`id\`, \`full_name\`, \`email\`, \`country\`, \`country_code\`, \`mobile\`, \`password_hash\`, \`timezone\`, \`token_version\`, \`created_at\`, \`updated_at\`)
VALUES
${userRows};`
    : '-- No users in SQLite'
}

${
  reminders.length
    ? `INSERT IGNORE INTO \`reminders\`
  (\`id\`, \`user_id\`, \`title\`, \`message\`, \`category\`, \`scheduled_at\`, \`timezone\`, \`repeat\`, \`priority\`, \`status\`, \`completed_at\`, \`series_id\`, \`created_at\`, \`updated_at\`)
VALUES
${reminderRows};`
    : '-- No reminders in SQLite'
}

SET FOREIGN_KEY_CHECKS = 1;
`;

  fs.writeFileSync(outPath, sql);
  console.log(`Wrote ${users.length} users and ${reminders.length} reminders → ${outPath}`);
  console.log('Next: phpMyAdmin → msgreminder_prod → Import → select this file → Go');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
